#!/usr/bin/env python3
"""Bake the monster eye into an N64 CI4 material and a ten-sided recessed socket."""
import argparse
import math
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'src/overlays/ovl_i1/bolse_robot_eye.inc'


def generate():
    source = Image.open(ROOT/'assets/bolse/monstrous-eye.png').convert('RGB').resize((64,64), Image.Resampling.LANCZOS)
    # Intensity keeps the same pupil and veins in both boss colors; sixteen tones keep the material bold.
    tones = [min(15, round((pixel[0]*.28+pixel[1]*.60+pixel[2]*.12)*15/255)) for pixel in source.getdata()]
    texture = [(tones[i]<<4)|tones[i+1] for i in range(0,len(tones),2)]
    palettes = {
        'Red': ['050306','130512','300511','56020a','8a0206','c00b03','e51a03','ff3005',
                'ff4b07','ff6f08','ff9612','ffc02a','ffdc4d','ffee80','fff2ae','fff6d8'],
        'Green': ['020405','041408','052c09','064b08','087b06','08ac02','18dc02','32f403',
                  '50ff06','72ff09','98ff16','bbff2c','d2ff4c','e3ff72','edff9a','f4ffca'],
    }
    vertices = []
    def vertex(x,y,z,u=0,v=0,color=(255,255,255)):
        vertices.append((round(x),round(y),round(z),u,v,*color,255))
    def face(points,color):
        for point in points:
            vertex(*point,color=color)
    def ring(rx,ry,z):
        return [(64+ry*math.sin(i*math.tau/10), -1+rx*math.cos(i*math.tau/10),z) for i in range(10)]
    # The original badge spans X=24..103, Y=-51..48, on torso limb 16 at Z=75.
    face([(104,49,76),(24,49,76),(24,-52,76)],(15,14,19))
    face([(104,49,76),(24,-52,76),(104,-52,76)],(15,14,19))
    for x,y,u,v in [(99,44,0,0),(29,44,0,2016),(29,-46,2016,2016),(99,44,0,0),(29,-46,2016,2016),(99,-46,2016,0)]:
        vertex(x,y,84,u,v)
    outer,crest,deep=ring(51,40,77),ring(45,29,94),ring(40,25,84)
    for near,far,base in [(outer,crest,38),(crest,deep,19)]:
        for i in range(10):
            j=(i+1)%10
            shade=round(base+(1+math.sin(i*math.tau/10))*17)
            color=(shade,round(shade*.85),round(shade*1.1))
            face([near[i],far[i],far[j]],color)
            face([near[i],far[j],near[j]],color)
    lines=['/* Generated by tools/bake_bolse_robot_eye.py. */','static u8 sBolseRobotEyeTexture[] = {']
    lines += ['    '+','.join(str(v) for v in texture[i:i+32])+',' for i in range(0,len(texture),32)]
    lines += ['};']
    for name,colors in palettes.items():
        palette=[]
        for color in colors:
            r,g,b=(int(color[i:i+2],16) for i in (0,2,4))
            value=((r>>3)<<11)|((g>>3)<<6)|((b>>3)<<1)|1
            palette.extend((value>>8,value&255))
        lines += [f'static u8 sBolseRobotEye{name}Palette[] = {{',
                  '    '+','.join(map(str,palette))+',','};']
    lines += ['static Vtx sBolseRobotEyeVertices[] = {']
    lines += ['    VTX('+','.join(map(str,v))+'),' for v in vertices]
    lines += ['};','static Gfx sBolseRobotEyeSocket[] = {','    gsDPPipeSync(),',
              '    gsDPSetCycleType(G_CYC_1CYCLE),','    gsSPClearGeometryMode(G_LIGHTING | G_FOG | G_CULL_BACK),',
              '    gsSPSetGeometryMode(G_ZBUFFER),','    gsDPSetRenderMode(G_RM_AA_ZB_OPA_SURF, G_RM_AA_ZB_OPA_SURF2),',
              '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_OFF),','    gsDPSetCombineMode(G_CC_SHADE, G_CC_SHADE),',
              '    gsSPVertex(sBolseRobotEyeVertices, 6, 0),','    gsSP2Triangles(0,1,2,0,3,4,5,0),','    gsSPEndDisplayList(),','};',
              'static Gfx sBolseRobotEyeIris[] = {','    gsDPPipeSync(),','    gsDPSetCombineMode(G_CC_DECALRGBA, G_CC_DECALRGBA),',
              '    gsSPTexture(0xFFFF, 0xFFFF, 0, G_TX_RENDERTILE, G_ON),',
              '    gsDPLoadTextureBlock_4b(sBolseRobotEyeTexture, G_IM_FMT_CI, 64, 64, 0, G_TX_CLAMP, G_TX_CLAMP, 6, 6, G_TX_NOLOD, G_TX_NOLOD),',
              '    gsSPVertex(&sBolseRobotEyeVertices[6], 6, 0),','    gsSP2Triangles(0,1,2,0,3,4,5,0),','    gsSPEndDisplayList(),','};',
              'static Gfx sBolseRobotEyeRim[] = {','    gsDPPipeSync(),','    gsDPSetTextureLUT(G_TT_NONE),','    gsDPSetCombineMode(G_CC_SHADE, G_CC_SHADE),',
              '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_OFF),']
    for offset in range(12,len(vertices),30):
        size=min(30,len(vertices)-offset)
        lines += [f'    gsSPVertex(&sBolseRobotEyeVertices[{offset}], {size}, 0),']
        for index in range(0,size,6):
            lines += [f'    gsSP2Triangles({index},{index+1},{index+2},0,{index+3},{index+4},{index+5},0),']
    lines += ['    gsSPEndDisplayList(),','};','',
              'static void Corneria_GrangaDrawMonsterEye(s32 robot) {',
              '    gSPDisplayList(gMasterDisp++, sBolseRobotEyeSocket);',
              '    gDPSetTextureLUT(gMasterDisp++, G_TT_RGBA16);',
              '    if (robot == 0) {', '        gDPLoadTLUT_pal16(gMasterDisp++, 0, sBolseRobotEyeGreenPalette);',
              '    } else {', '        gDPLoadTLUT_pal16(gMasterDisp++, 0, sBolseRobotEyeRedPalette);', '    }',
              '    gSPDisplayList(gMasterDisp++, sBolseRobotEyeIris);',
              '    gSPDisplayList(gMasterDisp++, sBolseRobotEyeRim);','}','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    result=generate()
    if args.check:
        if TARGET.read_text()!=result:
            raise SystemExit('Robot eye material needs rebuilding: python3 tools/bake_bolse_robot_eye.py')
        print('Monster-eye material and ten-sided socket match the source.')
    else:
        TARGET.write_text(result)
        print(TARGET)


if __name__=='__main__':
    main()

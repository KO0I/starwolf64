def masked(text):
    return re.sub(r'/\*[\s\S]*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
                  lambda m:re.sub(r'[^\n]',' ',m[0]),text)
def body(text,pattern,tail=False):
    mask=masked(text);m=re.search(pattern,mask,re.M)
    if not m:raise ValueError("Missing source declaration: "+pattern)
    start=m.start();cursor=mask.index("{",m.start());depth=1;cursor+=1
    while depth:
        if mask[cursor]=="{":depth+=1
        elif mask[cursor]=="}":depth-=1
        cursor+=1
    if tail:cursor=text.index(";",cursor)+1
    return text[start:cursor]
def function(text,name):
    return body(text,r'^[^\n;{}]*\b'+name+r'\s*\([^;{}]*\)\s*\{')

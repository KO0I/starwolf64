static const s32 sGlyphStarts[] = { 0, 52, 84, 128, 172 };

static void Multilock_DrawGlyph(s32 glyph) {
    s32 i;
    RCP_SetupDL(&gMasterDisp, SETUPDL_27);
    gSPTexture(gMasterDisp++, 0, 0, 0, G_TX_RENDERTILE, G_OFF);
    gSPClearGeometryMode(gMasterDisp++, G_LIGHTING | G_CULL_BACK | G_CULL_FRONT | G_TEXTURE_GEN);
    gDPSetCombineMode(gMasterDisp++, G_CC_PRIMITIVE, G_CC_PRIMITIVE);
    gDPSetPrimColor(gMasterDisp++, 0, 0, 255, (glyph == 0 || glyph == gMultilockCapacity) ? 255 : 0,
                    glyph == 0 ? 255 : 0, 255);
    for (i = sGlyphStarts[glyph]; i < sGlyphStarts[glyph + 1]; i += 4) {
        gSPVertex(gMasterDisp++, &sGlyphVertices[i], 4, 0);
        gSP2Triangles(gMasterDisp++, 0, 1, 2, 0, 0, 2, 3, 0);
    }
}

void Multilock_DrawItem(Item* item) {
    Graphics_SetScaleMtx(item->width * 0.1f);
    RCP_SetupDL(&gMasterDisp, SETUPDL_29);
    gSPTexture(gMasterDisp++, 2000, 2000, 0, G_TX_RENDERTILE, G_ON);
    gSPSetGeometryMode(gMasterDisp++, G_TEXTURE_GEN);
    gDPSetPrimColor(gMasterDisp++, 0, 0, 35, 105, 255, 255);
    gDPSetCombineLERP(gMasterDisp++, SHADE, 0, PRIMITIVE, 0, 0, 0, 0, PRIMITIVE,
                     SHADE, 0, PRIMITIVE, 0, 0, 0, 0, PRIMITIVE);
    gSPDisplayList(gMasterDisp++, D_10231A0);
    gSPClearGeometryMode(gMasterDisp++, G_TEXTURE_GEN);
    Matrix_Push(&gGfxMatrix);
    Matrix_Translate(gGfxMatrix, 0.0f, 0.0f, 11.0f, MTXF_APPLY);
    Matrix_SetGfxMtx(&gMasterDisp);
    Multilock_DrawGlyph(0);
    Matrix_Pop(&gGfxMatrix);
    Matrix_Push(&gGfxMatrix);
    Matrix_RotateY(gGfxMatrix, M_PI, MTXF_APPLY);
    Matrix_Translate(gGfxMatrix, 0.0f, 0.0f, 11.0f, MTXF_APPLY);
    Matrix_SetGfxMtx(&gMasterDisp);
    Multilock_DrawGlyph(0);
    Matrix_Pop(&gGfxMatrix);
}

void Multilock_DrawIndicators(void) {
    s32 targets[MULTILOCK_MAX_TARGETS];
    s32 count = Multilock_GetTargets(targets);
    s32 i;

    for (i = 0; i < count; i++) {
        Actor* actor = &gActors[targets[i]];
        Vec3f view = actor->lockOnViewPos;
        f32 scale;

        actor->lockOnViewPos.z = 100.0f;
        if (view.z >= 0.0f) {
            continue;
        }
        scale = VEC3F_MAG(&view);
        if (scale >= 20000.0f) {
            continue;
        }
        scale *= 0.0015f;
        if (scale < 1.2f) {
            scale = 1.2f;
        }
        if (scale > 100.0f) {
            scale = 100.0f;
        }
        FrameInterpolation_RecordOpenChild("MultilockIndicator", targets[i]);
        Matrix_Push(&gGfxMatrix);
        Matrix_Translate(gGfxMatrix, view.x, view.y, view.z, MTXF_APPLY);
        Matrix_Scale(gGfxMatrix, scale * 1.5f, scale * 1.5f, 1.0f, MTXF_APPLY);
        Matrix_SetGfxMtx(&gMasterDisp);
        RCP_SetupDL(&gMasterDisp, SETUPDL_67_OPTIONAL);
        gDPSetPrimColor(gMasterDisp++, 0, 0, 255, 0, 0, 255);
        gDPSetEnvColor(gMasterDisp++, 255, 0, 0, 255);
        gSPDisplayList(gMasterDisp++, D_1024F60);
        Matrix_Translate(gGfxMatrix, 26.0f, -28.0f, 0.0f, MTXF_APPLY);
        Matrix_SetGfxMtx(&gMasterDisp);
        Multilock_DrawGlyph(i + 1);
        Matrix_Pop(&gGfxMatrix);
        FrameInterpolation_RecordCloseChild();
    }
}
